"""Write the showcase film's beat scenes from the set and each beat (#435).

    python tools/showcase/build_scenes.py          # write demo/film/*.scene.toml
    python tools/showcase/build_scenes.py --check  # exit 1 if any is stale

Each beat in tools/showcase/film.toml names a fragment, demo/film/beats/
<id>.toml: its [scene], [camera] and [post_process], the beat's script
entity, and any components it adds to the set's props (an ascii_style on
the barrel, say). The scene is that fragment followed by demo/film/set.toml,
the clearing every beat shares, so the set is written once and a beat says
only what makes it that beat. Plain text, no TOML rewriting: a fragment may
add tables under the set's entities but must not repeat one, which the
parse at the end of each build catches.

Python 3.11+ (tomllib); no other packages.
"""

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FILM = ROOT / "tools" / "showcase" / "film.toml"
FILM_DIR = ROOT / "demo" / "film"


def header(beat):
    lines = [
        f"# Showcase film, beat {beat['id']}: {beat['title']} (#435).",
        "# GENERATED by tools/showcase/build_scenes.py from",
        f"# demo/film/beats/{beat['id']}.toml and demo/film/set.toml: edit those",
        "# and run it again. Captured by tools/showcase/capture.py; the",
        "# storyboard is docs/design/showcase-film.md.",
        "",
    ]
    return "\n".join(lines)


def build(beat):
    fragment = (FILM_DIR / "beats" / f"{beat['id']}.toml").read_text(encoding="utf-8")
    set_text = (FILM_DIR / "set.toml").read_text(encoding="utf-8")
    text = header(beat) + fragment.rstrip() + "\n\n" + set_text
    try:
        tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise SystemExit(f"{beat['id']}: the fragment and the set don't make one scene: {e}")
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a scene is out of date")
    args = ap.parse_args()
    film = tomllib.loads(FILM.read_text(encoding="utf-8"))
    stale = []
    for beat in film["beat"]:
        path = FILM_DIR / f"{beat['id']}.scene.toml"
        text = build(beat)
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        if args.check:
            stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale (run tools/showcase/build_scenes.py): " + ", ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
