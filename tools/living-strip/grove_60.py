"""Write the 60-tree Woozy Grove: the grove's 38 trees plus copies of the first 22,
16 m further in, the scene the book's "What it costs" table measures at 60 (#532).

    python tools/living-strip/grove_60.py            # writes demo/woozy_grove_60.scene.toml
    flint-player demo/woozy_grove_60.scene.toml --schemas schemas --exit-after 60

A copy keeps its tree's species, lineage, turn and scale, so it shares that tree's
skeleton and rig, but it has a name of its own (`<tree>_far`), and shape seeds come
from the name: every copy needs poses of its own, which is the load being measured.
The copies get no trunk colliders; nothing walks out that far.
"""

import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
GROVE = ROOT / "demo" / "woozy_grove.scene.toml"
OUT = ROOT / "demo" / "woozy_grove_60.scene.toml"
COPIES = 22
BACK = 16.0


def toml_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{k} = {toml_value(v)}" for k, v in value.items()) + " }"
    raise TypeError(f"can't write {value!r}")


def main():
    text = GROVE.read_text(encoding="utf-8")
    entities = tomllib.loads(text)["entities"]
    trees = [(name, e) for name, e in entities.items() if "living_prop" in e]
    if len(trees) + COPIES != 60:
        sys.exit(f"the grove has {len(trees)} trees, so {COPIES} copies don't make 60")

    lines = [
        "# GENERATED by tools/living-strip/grove_60.py from woozy_grove.scene.toml: don't edit,",
        "# run the script again. The grove plus copies of its first 22 trees, 16 m further in,",
        "# for the 60-tree rows of the book's \"What it costs\" table (#532).",
        "",
        text.rstrip("\n"),
        "",
        f"# --- {COPIES} more, {BACK:g} m further in: each its own name, so its own poses ---",
    ]
    for name, e in trees[:COPIES]:
        copy = f"{name}_far"
        transform = dict(e["transform"])
        x, y, z = transform["position"]
        transform["position"] = [x, y, round(z + BACK, 3)]
        lines.append("")
        for component in ("transform", "model", "living_prop"):
            fields = transform if component == "transform" else e[component]
            lines.append(f"[entities.{copy}.{component}]")
            lines.extend(f"{k} = {toml_value(v)}" for k, v in fields.items())
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(trees) + COPIES} living trees")


if __name__ == "__main__":
    main()
