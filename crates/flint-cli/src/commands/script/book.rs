//! The book against the declared script API (#695).
//!
//! ```bash
//! flint script api --book            # write the generated reference and tables
//! flint script api --check-book      # exit 1 if any is stale or a chapter names a ghost (CI)
//! ```
//!
//! Two things keep `docs/book` honest:
//!
//! - **Generated text.** `src/reference/script-api.md` is written whole from
//!   the registry: the conventions, the callbacks and one table per module.
//!   Any chapter can hold a generated table between
//!   `<!-- script-api:begin <selector> -->` and `<!-- script-api:end -->`;
//!   the selector is space-separated `module:<name>`, function names, and
//!   `callbacks`. The scripting chapter's tables are these.
//! - **No ghosts.** Every call written in a chapter's code (spans, and
//!   fenced blocks that aren't Rust or a shell) names a declared function at
//!   an arity it is declared at, a callback, a Rhai built-in, a function the
//!   book defines with `fn`, or a name in `script-api-allow.txt` beside
//!   `src/`. A row's `name(a, b[, c])` claims both arities.

use flint_script::api::registry::{ApiEntry, ApiListing, CallbackDoc, CONVENTIONS};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The generated reference, from the book's directory.
pub const REFERENCE: &str = "src/reference/script-api.md";
/// Names the ghost check lets through, one per line, `# why` after.
pub const ALLOW: &str = "script-api-allow.txt";
const BEGIN: &str = "<!-- script-api:begin";
const END: &str = "<!-- script-api:end -->";
const GENERATED: &str = "<!-- Generated by `flint script api --book` from the engine's \
                         declarations (crates/flint-script/src/api/): edit the doc there, \
                         not here. CI's headless job runs --check-book. -->";

/// What a call in the book may name.
pub struct Known {
    /// Declared name -> the arities it is declared at.
    pub declared: BTreeMap<String, BTreeSet<usize>>,
    pub callbacks: BTreeMap<String, usize>,
    /// Rhai's own functions (its packages, from its metadata) and keywords.
    pub builtins: BTreeSet<String>,
    /// Allowed anywhere.
    pub allow: BTreeSet<String>,
    /// Allowed on one page (its path under `src/`, with `/`); `*` is the
    /// whole page.
    pub allow_on: BTreeMap<String, BTreeSet<String>>,
}

/// Rhai syntax that looks like a call, and functions Rhai resolves itself
/// rather than through a package.
const RHAI_KEYWORDS: &[&str] = &[
    "if",
    "else",
    "while",
    "for",
    "in",
    "loop",
    "do",
    "until",
    "switch",
    "return",
    "fn",
    "let",
    "const",
    "throw",
    "try",
    "catch",
    "import",
    "export",
    "as",
    "private",
    "this",
    "global",
    "Fn",
    "call",
    "curry",
    "is_def_fn",
    "is_def_var",
    "is_shared",
    "type_of",
    "print",
    "debug",
    "eval",
];

impl Known {
    /// From the engine's listing, the signatures of Rhai's own packages
    /// (`package_signatures`) and the allowlist's text.
    pub fn new(listing: &ApiListing, package_signatures: &[String], allow: &str) -> Self {
        let mut declared: BTreeMap<String, BTreeSet<usize>> = BTreeMap::new();
        for e in &listing.declared {
            declared
                .entry(e.name.to_string())
                .or_default()
                .insert(e.params.len());
        }
        for u in &listing.undeclared {
            declared
                .entry(u.name.clone())
                .or_default()
                .insert(u.params.len());
        }
        let callbacks = listing
            .callbacks
            .iter()
            .map(|c| (c.name.to_string(), c.params.len()))
            .collect();
        let mut builtins: BTreeSet<String> = RHAI_KEYWORDS.iter().map(|s| s.to_string()).collect();
        builtins.extend(
            package_signatures
                .iter()
                .filter_map(|sig| flint_script::api::registry::parse_signature(sig))
                .map(|f| f.name),
        );
        let (mut anywhere, mut allow_on) = (BTreeSet::new(), BTreeMap::new());
        for line in allow.lines() {
            let line = line.split('#').next().unwrap_or("").trim();
            match line.split_once(':') {
                Some((page, names)) => {
                    let set: &mut BTreeSet<String> =
                        allow_on.entry(page.trim().to_string()).or_default();
                    set.extend(names.split_whitespace().map(str::to_string));
                }
                None => anywhere.extend(line.split_whitespace().map(str::to_string)),
            }
        }
        Known {
            declared,
            callbacks,
            builtins,
            allow: anywhere,
            allow_on,
        }
    }
}

/// The signatures Rhai's packages register: everything the engine lists
/// with packages (`gen_fn_signatures(true)`), less what it lists without
/// them (Flint's and a host's).
pub fn package_signatures(with_packages: Vec<String>, own: Vec<String>) -> Vec<String> {
    let own: BTreeSet<String> = own.into_iter().collect();
    with_packages
        .into_iter()
        .filter(|s| !own.contains(s))
        .collect()
}

