/// Plain text for a table cell or a list: identifiers with an underscore
/// and `#{...}` map shapes as code, the rest escaped.
fn cell(text: &str) -> String {
    let chars: Vec<char> = text.chars().collect();
    let mut out = String::new();
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        if c == '#' && chars.get(i + 1) == Some(&'{') {
            if let Some(end) = (i + 2..chars.len()).find(|&j| chars[j] == '}') {
                let s: String = chars[i..=end].iter().collect();
                let _ = write!(out, "`{}`", s.replace('|', "\\|"));
                i = end + 1;
                continue;
            }
        }
        let starts_word = i == 0 || !is_ident(chars[i - 1]);
        if starts_word && is_ident_start(c) {
            let end = (i..chars.len())
                .find(|&j| !is_ident(chars[j]))
                .unwrap_or(chars.len());
            let word: String = chars[i..end].iter().collect();
            if word.contains('_') && word.trim_matches('_') == word {
                // `name(args)` as one span when the parentheses close soon
                let call_end = (chars.get(end) == Some(&'('))
                    .then(|| (end..chars.len().min(end + 40)).find(|&j| chars[j] == ')'))
                    .flatten();
                let end = call_end.map_or(end, |j| j + 1);
                let code: String = chars[i..end].iter().collect();
                let _ = write!(out, "`{}`", code.replace('|', "\\|"));
                i = end;
                continue;
            } else {
                out.push_str(&word);
            }
            i = end;
            continue;
        }
        match c {
            '\\' | '|' | '*' | '_' | '<' | '>' | '[' | ']' | '`' => {
                out.push('\\');
                out.push(c);
            }
            _ => out.push(c),
        }
        i += 1;
    }
    out
}

fn signature_cell(e: &ApiEntry) -> String {
    let params: Vec<String> = e
        .params
        .iter()
        .map(|p| format!("{}: {}", p.name, p.kind))
        .collect();
    let typed = if e.typed { " *(typed)*" } else { "" };
    format!("`{}({})`{typed}", e.name, params.join(", "))
}

fn returns_cell(e: &ApiEntry) -> String {
    match e.returns {
        None => "—".to_string(),
        Some((kind, "")) => format!("`{kind}`"),
        Some((kind, note)) => format!("`{kind}`: {}", cell(note)),
    }
}

fn function_table(entries: &[&ApiEntry]) -> String {
    let mut out = String::from("| Function | Returns | Description |\n|---|---|---|\n");
    for e in entries {
        let _ = writeln!(
            out,
            "| {} | {} | {} |",
            signature_cell(e),
            returns_cell(e),
            cell(e.doc)
        );
    }
    out
}

fn callback_table(callbacks: &[CallbackDoc]) -> String {
    let mut out = String::from("| Callback | When it runs |\n|---|---|\n");
    for c in callbacks {
        let _ = writeln!(
            out,
            "| `fn {}({})` | {} |",
            c.name,
            c.params.join(", "),
            cell(c.doc)
        );
    }
    out
}

/// The modules in declaration order.
fn modules(listing: &ApiListing) -> Vec<&'static str> {
    let mut modules: Vec<&str> = Vec::new();
    for e in &listing.declared {
        if !modules.contains(&e.module) {
            modules.push(e.module);
        }
    }
    modules
}

/// The whole reference page.
pub fn reference_page(listing: &ApiListing) -> String {
    let mut out = String::new();
    out.push_str("# Script API Reference\n\n");
    out.push_str(GENERATED);
    out.push_str("\n\n");
    let _ = writeln!(
        out,
        "Every function a Flint script can call: {} declarations in {} modules, and the {} \
         callbacks the engine calls on a script that defines them. The engine writes this page \
         from the same declarations that register the functions (ADR 0116), so it can't name \
         one that isn't there or miss one that is. `flint script api` prints the same list in \
         a terminal (`--filter draw` narrows it) and `--json` gives it as data. A game whose \
         player extensions declare functions of their own lists them from its own binary with \
         `ScriptSystem::api_listing` (see [Player Extensions](../guides/player-extensions.md)).\n",
        listing.declared.len(),
        modules(listing).len(),
        listing.callbacks.len(),
    );
    out.push_str(
        "What each function is for, with examples, is in [Scripting](../concepts/scripting.md) \
         and the chapters it links. Parameter kinds: `num` is an int or a float, `int` an int \
         or a whole float, `entity` an entity id (`entity?` one that may be missing: no \
         warning), `color` `[r, g, b]`, `[r, g, b, a]` or `\"#rrggbb(aa)\"`, `any` whatever \
         the description says, `fn` a function pointer (`Fn(\"name\")`). A function marked \
         *(typed)* takes exactly the types listed.\n\n",
    );
    out.push_str("## Conventions\n\n");
    for (name, rule) in CONVENTIONS {
        let _ = writeln!(out, "- **{}**: {}", name.replace('_', " "), cell(rule));
    }
    out.push_str("\n## Callbacks\n\n");
    out.push_str(&callback_table(&listing.callbacks));
    out.push_str("\n## Modules\n\n");
    let mods = modules(listing);
    let index: Vec<String> = mods
        .iter()
        .map(|m| {
            let n = listing.declared.iter().filter(|e| e.module == *m).count();
            format!("[{m}](#{m}) ({n})")
        })
        .collect();
    out.push_str(&index.join(" · "));
    out.push('\n');
    for m in mods {
        let entries: Vec<&ApiEntry> = listing.declared.iter().filter(|e| e.module == m).collect();
        let _ = write!(out, "\n## {m}\n\n");
        out.push_str(&function_table(&entries));
    }
    if !listing.undeclared.is_empty() {
        out.push_str("\n## Undeclared\n\nRegistered on the Rhai engine directly: Rust types, no names or docs.\n\n");
        for u in &listing.undeclared {
            let _ = writeln!(out, "- `{}`", u.signature);
        }
    }
    out
}

/// One region's generated body (between its markers).
pub fn region(selector: &str, listing: &ApiListing) -> Result<String, String> {
    let mut picked: Vec<&ApiEntry> = Vec::new();
    let mut callbacks = false;
    for token in selector.split_whitespace() {
        if token == "callbacks" {
            callbacks = true;
            continue;
        }
        let found: Vec<&ApiEntry> = match token.strip_prefix("module:") {
            Some(m) => listing.declared.iter().filter(|e| e.module == m).collect(),
            None => listing
                .declared
                .iter()
                .filter(|e| e.name == token)
                .collect(),
        };
        if found.is_empty() {
            let hint = if listing.declared.iter().any(|e| e.module == token) {
                format!(" (the module is `module:{token}`)")
            } else {
                String::new()
            };
            return Err(format!("`{token}` names no declared function{hint}"));
        }
        for e in found {
            if !picked.iter().any(|p| std::ptr::eq(*p, e)) {
                picked.push(e);
            }
        }
    }
    if callbacks && !picked.is_empty() {
        return Err("a region lists callbacks or functions, not both".into());
    }
    let table = if callbacks {
        callback_table(&listing.callbacks)
    } else if picked.is_empty() {
        return Err("an empty selector".into());
    } else {
        function_table(&picked)
    };
    Ok(format!("{GENERATED}\n\n{table}"))
}

/// `page` with every region's body regenerated.
pub fn splice_regions(page: &str, listing: &ApiListing) -> Result<String, String> {
    let mut out = String::new();
    let mut rest = page;
    while let Some(start) = rest.find(BEGIN) {
        let open_end = rest[start..]
            .find("-->")
            .map(|i| start + i + 3)
            .ok_or("an unclosed script-api:begin comment")?;
        let selector = rest[start + BEGIN.len()..open_end - 3].trim();
        let line = page[..page.len() - rest.len() + start].lines().count() + 1;
        let close = rest[open_end..]
            .find(END)
            .map(|i| open_end + i)
            .ok_or_else(|| format!("line {line}: script-api:begin with no {END}"))?;
        let body = region(selector, listing).map_err(|e| format!("line {line}: {e}"))?;
        out.push_str(&rest[..open_end]);
        out.push_str("\n");
        out.push_str(&body);
        out.push('\n');
        rest = &rest[close..];
        out.push_str(END);
        rest = &rest[END.len()..];
    }
    out.push_str(rest);
    Ok(out)
}

